const RULES = EMOJI.map(([emoji, words]) => [emoji, new RegExp(`\\b(${words})(s|es)?\\b`, 'i')] as const);

/** A picture for a Product with no photo: guessed from its name, then its category, else a shopping trolley. */
export function emojiFor(name: string, category?: string | null): string {
  for (const text of [name, category ?? '']) {
    const hit = RULES.find(([, re]) => re.test(text));
    if (hit) return hit[0];
  }
  return '🛒';
}
